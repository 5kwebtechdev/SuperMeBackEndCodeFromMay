package com.superme.admin.dto;

// ChallengeStatistics.java
public class ChallengeStatistics {
    private long totalChallenges;
    private long totalQuiz;
    private long totalPuzzles;
    private long totalArticles;
    
    // Getters and setters
    public long getTotalChallenges() { return totalChallenges; }
    public void setTotalChallenges(long totalChallenges) { this.totalChallenges = totalChallenges; }
    
    public long getTotalQuiz() { return totalQuiz; }
    public void setTotalQuiz(long totalQuiz) { this.totalQuiz = totalQuiz; }
    
    public long getTotalPuzzles() { return totalPuzzles; }
    public void setTotalPuzzles(long totalPuzzles) { this.totalPuzzles = totalPuzzles; }
    
    public long getTotalArticles() { return totalArticles; }
    public void setTotalArticles(long totalArticles) { this.totalArticles = totalArticles; }
}
